#!/usr/bin/env python3
"""Build audits/card-usage.md: how often every starting (skill) card is used, and where.

Counts each card link in a move's Requires, Noticed by, When or Gives across characters,
events, locations, items and tags. A card in `A OR B` counts once for each card. Under the
table, every use is listed by card: the move, the field, the file.

audits/ is gitignored and rebuilt by the edit hook. Run by hand:
    python tools/build_card_usage.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "audits" / "card-usage.md"
KINDS = ("characters", "events", "locations", "items", "tags")
FIELDS = ("Requires", "Noticed by", "When", "Gives")
FIELD = re.compile(r"^\s*-\s*\*\*(Requires|Noticed by|When|Gives):\*\*\s*(.*)$")
CARD = re.compile(r"cards/([a-z0-9-]+)\.md")


def starting_cards() -> list[str]:
    return sorted(p.stem for p in (ROOT / "cards").glob("*.md")
                  if not p.stem.startswith("_") and "**Pool:** Starting card" in p.read_text(encoding="utf-8"))


def uses(cards: list[str]) -> dict[str, list[tuple[str, str, str]]]:
    """card -> [(field, move heading, file)]."""
    out = {c: [] for c in cards}
    for k in KINDS:
        for p in sorted((ROOT / k).rglob("*.md")):
            if p.name.startswith("_") or p.name == "index.md":
                continue
            move = ""
            for line in p.read_text(encoding="utf-8").splitlines():
                if line.startswith("### "):
                    move = line[4:].strip()
                m = FIELD.match(line)
                if not m:
                    continue
                for c in CARD.findall(m.group(2)):
                    if c in out:
                        out[c].append((m.group(1), move, p.relative_to(ROOT).as_posix()))
    return out


def main() -> None:
    cards = starting_cards()
    u = uses(cards)
    order = sorted(cards, key=lambda c: (-len(u[c]), c))
    lines = ["# Card usage", "",
             "Every starting card's uses in Requires, Noticed by, When and Gives. Generated by "
             "`tools/build_card_usage.py`; do not edit.", "",
             "| Card | " + " | ".join(FIELDS) + " | Total |",
             "|---|" + "---:|" * (len(FIELDS) + 1)]
    for c in order:
        n = [sum(1 for f, _, _ in u[c] if f == field) for field in FIELDS]
        lines.append(f"| {c} | " + " | ".join(str(x) for x in n) + f" | **{len(u[c])}** |")
    unused = [c for c in order if not u[c]]
    if unused:
        lines += ["", "**Unused:** " + ", ".join(unused)]
    for c in order:
        if not u[c]:
            continue
        lines += ["", f"## {c} ({len(u[c])})", ""]
        lines += [f"- {field}: {move or '(no heading)'} — `{f}`" for field, move, f in u[c]]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT).as_posix()}: {len(cards)} cards, {sum(len(v) for v in u.values())} uses")


if __name__ == "__main__":
    main()
