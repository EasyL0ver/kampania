#!/usr/bin/env python3
"""Build .crossnote/parser.js: Markdown Preview Enhanced renders [@field](file.md) as
that file's field value (same model as entity_fields() in validate.py).

MPE runs parser.js without file access, so every entity's fields are baked in as a
table. Rerun after renaming anything:  python tools/build_names.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KINDS = ["characters", "locations", "events", "items", "cards"]
FIELD = re.compile(r"^\s*(?:-\s*)?\*\*([^*:]+):\*\*\s*(.*?)\s*$")
REF = re.compile(r"\[@([a-z0-9-]+)\]\(([^)#\s]+\.md)\)")
LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def label(s: str) -> str:
    return re.sub(r"\s+", "-", s.strip().lower())


def raw_fields(path: Path) -> dict[str, str]:
    fields: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if "name" not in fields and line.startswith("# "):
            fields["name"] = line[2:].strip()
        m = FIELD.match(line)
        if m:
            fields.setdefault(label(m.group(1)), m.group(2))
    return fields


def render(text: str, src: Path, table: dict, depth: int = 0) -> str:
    """Resolve nested refs (relative to the file holding the value), keep link text only."""
    def sub(m):
        target = (src.parent / m.group(2)).resolve()
        key = target.relative_to(ROOT).as_posix() if target.is_relative_to(ROOT) else None
        value = table.get(key, {}).get(m.group(1)) if key else None
        return render(value, target, table, depth + 1) if value is not None and depth < 4 else m.group(0)
    text = REF.sub(sub, text)
    return re.sub(r"\*\*|`", "", LINK.sub(r"\1", text))


def main() -> None:
    files = [p for k in KINDS for p in (ROOT / k).rglob("*.md")
             if not p.name.startswith("_") and p.name != "index.md"]
    raw = {p.relative_to(ROOT).as_posix(): raw_fields(p) for p in files}
    table = {key: {f: render(v, ROOT / key, raw) for f, v in fields.items()} for key, fields in raw.items()}
    out = ROOT / ".crossnote" / "parser.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text(TEMPLATE.replace("__TABLE__", json.dumps(table, ensure_ascii=False, indent=0)),
                   encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT).as_posix()}: {len(table)} files")


TEMPLATE = r"""// GENERATED by tools/build_names.py: do not edit. Rerun it after renaming anything.
// Markdown Preview Enhanced: render [@field](file.md) as that file's field value.
({
  onWillParseMarkdown: async function (markdown) {
    const T = __TABLE__;
    const keys = Object.keys(T);
    // The href is relative to an unknown file: match the one table path it ends with.
    const find = (href) => {
      const tail = "/" + decodeURIComponent(href).replace(/^(\.\.?\/)+/, "");
      const hits = keys.filter((k) => ("/" + k).endsWith(tail));
      return hits.length === 1 ? T[hits[0]] : null;
    };
    return markdown.replace(/\[@([a-z0-9-]+)\]\(([^)\s]+)\)/g, (all, field, href) => {
      const f = find(href.split("#")[0]);
      const v = f && f[field];
      return v != null ? `[${v}](${href})` : `[⚠ @${field}](${href})`;
    });
  },
  onDidParseMarkdown: async function (html) {
    return html;
  },
})
"""

if __name__ == "__main__":
    main()
